def analyze_invoices(
    plan: dict[str, Any],
) -> dict[str, Any]:
    records = get_all_invoices()

    departments = plan.get("departments") or []
    vendors = plan.get("vendors") or []
    risks = plan.get("risks") or []
    statuses = plan.get("statuses") or []

    min_amount = plan.get("min_amount")
    max_amount = plan.get("max_amount")

    if departments:
        department_set = {
            value.lower()
            for value in departments
        }

        records = [
            record
            for record in records
            if record["department"].lower()
            in department_set
        ]

    if vendors:
        vendor_set = {
            value.lower()
            for value in vendors
        }

        records = [
            record
            for record in records
            if record["vendor"].lower()
            in vendor_set
        ]

    if risks:
        risk_set = {
            value.lower()
            for value in risks
        }

        records = [
            record
            for record in records
            if record["risk"].lower()
            in risk_set
        ]

    if statuses:
        status_set = {
            value.lower()
            for value in statuses
        }

        records = [
            record
            for record in records
            if record["status"].lower()
            in status_set
        ]

    if min_amount is not None:
        records = [
            record
            for record in records
            if float(record["amount"])
            >= float(min_amount)
        ]

    if max_amount is not None:
        records = [
            record
            for record in records
            if float(record["amount"])
            <= float(max_amount)
        ]

    records.sort(
        key=lambda record: float(
            record["amount"]
        ),
        reverse=True,
    )

    total_spend = round(
        sum(
            float(record["amount"])
            for record in records
        ),
        2,
    )

    average_amount = (
        round(
            total_spend / len(records),
            2,
        )
        if records
        else 0
    )

    summary = {
        "count": len(records),
        "total_spend": total_spend,
        "average_amount": average_amount,
        "pending_count": sum(
            1
            for record in records
            if record["status"].lower() == "pending"
        ),
        "approved_count": sum(
            1
            for record in records
            if record["status"].lower() == "approved"
        ),
        "review_count": sum(
            1
            for record in records
            if record["status"].lower() == "review"
        ),
        "high_risk_count": sum(
            1
            for record in records
            if record["risk"].lower() == "high"
        ),
        "medium_risk_count": sum(
            1
            for record in records
            if record["risk"].lower() == "medium"
        ),
        "low_risk_count": sum(
            1
            for record in records
            if record["risk"].lower() == "low"
        ),
    }

    department_breakdown = _build_breakdown(
        records,
        "department",
    )

    vendor_breakdown = _build_breakdown(
        records,
        "vendor",
    )

    risk_breakdown = _build_simple_breakdown(
        records,
        "risk",
    )

    status_breakdown = _build_simple_breakdown(
        records,
        "status",
    )

    largest_invoice = (
        records[0]
        if records
        else None
    )

    smallest_invoice = (
        min(
            records,
            key=lambda record: float(
                record["amount"]
            ),
        )
        if records
        else None
    )

    return {
        "filters": {
            "departments": departments,
            "vendors": vendors,
            "risks": risks,
            "statuses": statuses,
            "min_amount": min_amount,
            "max_amount": max_amount,
        },
        "summary": summary,
        "department_breakdown": department_breakdown,
        "vendor_breakdown": vendor_breakdown,
        "risk_breakdown": risk_breakdown,
        "status_breakdown": status_breakdown,
        "largest_invoice": largest_invoice,
        "smallest_invoice": smallest_invoice,
        "records": records,
    }


def _build_breakdown(
    records: list[dict[str, Any]],
    field: str,
) -> list[dict[str, Any]]:
    groups: dict[str, list[dict[str, Any]]] = {}

    for record in records:
        name = str(record[field])

        groups.setdefault(
            name,
            [],
        ).append(record)

    results = []

    for name, group in groups.items():
        total_spend = round(
            sum(
                float(record["amount"])
                for record in group
            ),
            2,
        )

        average_amount = round(
            total_spend / len(group),
            2,
        )

        result = {
            field: name,
            "count": len(group),
            "total_spend": total_spend,
            "average_amount": average_amount,
            "high_risk_count": sum(
                1
                for record in group
                if record["risk"].lower() == "high"
            ),
            "medium_risk_count": sum(
                1
                for record in group
                if record["risk"].lower() == "medium"
            ),
            "low_risk_count": sum(
                1
                for record in group
                if record["risk"].lower() == "low"
            ),
            "pending_count": sum(
                1
                for record in group
                if record["status"].lower()
                == "pending"
            ),
            "approved_count": sum(
                1
                for record in group
                if record["status"].lower()
                == "approved"
            ),
            "review_count": sum(
                1
                for record in group
                if record["status"].lower()
                == "review"
            ),
        }

        results.append(result)

    results.sort(
        key=lambda item: item["total_spend"],
        reverse=True,
    )

    return results


def _build_simple_breakdown(
    records: list[dict[str, Any]],
    field: str,
) -> list[dict[str, Any]]:
    groups: dict[str, list[dict[str, Any]]] = {}

    for record in records:
        name = str(record[field])

        groups.setdefault(
            name,
            [],
        ).append(record)

    results = []

    for name, group in groups.items():
        total_spend = round(
            sum(
                float(record["amount"])
                for record in group
            ),
            2,
        )

        results.append(
            {
                field: name,
                "count": len(group),
                "total_spend": total_spend,
                "average_amount": round(
                    total_spend / len(group),
                    2,
                ),
            }
        )

    results.sort(
        key=lambda item: item["count"],
        reverse=True,
    )

    return results