def get_department_spending(
    department: str | None = None,
) -> list[dict[str, Any]]:
    records = get_all_invoices()

    if department:
        records = [
            record
            for record in records
            if record["department"].lower()
            == department.lower()
        ]

    groups: dict[str, dict[str, Any]] = {}

    for record in records:
        name = record["department"]

        if name not in groups:
            groups[name] = {
                "department": name,
                "total_spending": 0.0,
                "invoice_count": 0,
            }

        groups[name]["total_spending"] += float(
            record["amount"]
        )
        groups[name]["invoice_count"] += 1

    results = list(groups.values())

    for result in results:
        result["total_spending"] = round(
            result["total_spending"],
            2,
        )

    results.sort(
        key=lambda item: item["total_spending"],
        reverse=True,
    )

    return results


