def replace_invoices(
    invoices: list[dict[str, Any]],
) -> int:
    with engine.begin() as connection:
        connection.execute(
            text("DELETE FROM invoices")
        )

        connection.execute(
            text(
                """
                INSERT INTO invoices (
                    vendor,
                    department,
                    amount,
                    status,
                    risk
                )
                VALUES (
                    :vendor,
                    :department,
                    :amount,
                    :status,
                    :risk
                )
                """
            ),
            invoices,
        )

    return len(invoices)


def get_all_invoices() -> list[dict[str, Any]]:
    with engine.connect() as connection:
        rows = connection.execute(
            text(
                """
                SELECT
                    id,
                    vendor,
                    department,
                    amount,
                    status,
                    risk
                FROM invoices
                ORDER BY amount DESC
                """
            )
        ).mappings().all()

    return [
        dict(row)
        for row in rows
    ]


def get_recent_invoices(
    limit: int = 8,
) -> list[dict[str, Any]]:
    records = get_all_invoices()

    records.sort(
        key=lambda record: record["id"],
        reverse=True,
    )

    return records[:limit]


def get_dashboard_summary() -> dict[str, Any]:
    records = get_all_invoices()

    return {
        "total_invoices": len(records),
        "pending_invoices": sum(
            1
            for record in records
            if record["status"].lower() == "pending"
        ),
        "high_risk_invoices": sum(
            1
            for record in records
            if record["risk"].lower() == "high"
        ),
        "total_spend": round(
            sum(
                float(record["amount"])
                for record in records
            ),
            2,
        ),
        "department_count": len(
            {
                record["department"]
                for record in records
            }
        ),
    }


def get_risk_distribution() -> list[dict[str, Any]]:
    records = get_all_invoices()

    groups: dict[str, int] = {}

    for record in records:
        risk = record["risk"]

        groups[risk] = groups.get(risk, 0) + 1

    return sorted(
        [
            {
                "risk": risk,
                "count": count,
            }
            for risk, count in groups.items()
        ],
        key=lambda item: item["count"],
        reverse=True,
    )


